func v1TestChunk(t testing.TB, header SegmentHeader, sequence uint64, pssKB uint64) []byte {
	t.Helper()
	record, _, _, err := encodeRecord(
		Event{Type: EventMemory, Memory: &MemoryEvent{PSSKB: pssKB}},
		recordEncodeState{lastElapsedUS: int64(header.SegmentStartElapsedUS)},
	)
	if err != nil {
		t.Fatal(err)
	}
	rawCRC := crc32.ChecksumIEEE(record)
	chunk := make([]byte, v1ChunkHeaderBytes+len(record)+v1CommitTrailerBytes)
	copy(chunk, v1ChunkMagic)
	binary.LittleEndian.PutUint16(chunk[4:6], v1ChunkHeaderBytes)
	binary.LittleEndian.PutUint64(chunk[8:16], sequence)
	binary.LittleEndian.PutUint32(chunk[16:20], uint32(len(record)))
	binary.LittleEndian.PutUint32(chunk[20:24], uint32(len(record)))
	binary.LittleEndian.PutUint32(chunk[24:28], 1)
	binary.LittleEndian.PutUint32(chunk[28:32], rawCRC)
	binary.LittleEndian.PutUint32(chunk[32:36], crc32.ChecksumIEEE(chunk[:32]))
	copy(chunk[v1ChunkHeaderBytes:], record)
	trailer := chunk[v1ChunkHeaderBytes+len(record):]
	copy(trailer, v1CommitMagic)
	binary.LittleEndian.PutUint64(trailer[4:12], sequence)
	binary.LittleEndian.PutUint32(trailer[12:16], uint32(len(record)))
	binary.LittleEndian.PutUint32(trailer[16:20], uint32(len(record)))
	binary.LittleEndian.PutUint32(trailer[20:24], rawCRC)
	return chunk
}

