func TestV1ReaderRejectsOversizedStoredPayloadBeforeReadingIt(t *testing.T) {
	path, firstPosition := writeV1Fixture(t)
	raw, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	chunkOffset := int(v1ArenaOffset) + firstPosition
	binary.LittleEndian.PutUint32(raw[chunkOffset+16:chunkOffset+20], uint32(maxStoredChunkSize+1))
	binary.LittleEndian.PutUint32(raw[chunkOffset+32:chunkOffset+36], crc32.ChecksumIEEE(raw[chunkOffset:chunkOffset+32]))
	for _, offset := range []int{int(v1SuperblockAOffset), int(v1SuperblockBOffset)} {
		binary.LittleEndian.PutUint64(raw[offset+16:offset+24], uint64(maxStoredChunkSize*2))
		binary.LittleEndian.PutUint32(
			raw[offset+int(v1SuperblockBytes)-4:offset+int(v1SuperblockBytes)],
			crc32.ChecksumIEEE(raw[offset:offset+int(v1SuperblockBytes)-4]),
		)
	}
	if err := os.WriteFile(path, raw, 0o600); err != nil {
		t.Fatal(err)
	}

	_, err = StreamFileWithResult(path, nil)
	if err == nil || !strings.Contains(err.Error(), "stored length") {
		t.Fatalf("error = %v", err)
	}
}

func TestV1ReaderRejectsValidChecksumSuperblocksWithImpossibleState(t *testing.T) {
	tests := []struct {
		name   string
		mutate func([]byte)
	}{
		{name: "zero generation", mutate: func(block []byte) { binary.LittleEndian.PutUint64(block[8:16], 0) }},
		{name: "zero arena", mutate: func(block []byte) { binary.LittleEndian.PutUint64(block[16:24], 0) }},
		{name: "head beyond arena", mutate: func(block []byte) { binary.LittleEndian.PutUint64(block[24:32], math.MaxUint64) }},
		{name: "tail beyond arena", mutate: func(block []byte) { binary.LittleEndian.PutUint64(block[32:40], math.MaxUint64) }},
		{name: "used beyond arena", mutate: func(block []byte) { binary.LittleEndian.PutUint64(block[40:48], math.MaxUint64) }},
		{name: "first after next", mutate: func(block []byte) {
			binary.LittleEndian.PutUint64(block[48:56], 9)
			binary.LittleEndian.PutUint64(block[56:64], 8)
		}},
		{name: "count differs from sequence window", mutate: func(block []byte) {
			binary.LittleEndian.PutUint64(block[64:72], 1)
			binary.LittleEndian.PutUint64(block[48:56], 2)
			binary.LittleEndian.PutUint64(block[56:64], 8)
		}},
		{name: "wraps exceed evicted chunks", mutate: func(block []byte) {
			binary.LittleEndian.PutUint64(block[72:80], 2)
			binary.LittleEndian.PutUint64(block[80:88], 1)
		}},
		{name: "evicted bytes exceed generated bytes", mutate: func(block []byte) {
			binary.LittleEndian.PutUint64(block[88:96], math.MaxUint64)
		}},
		{name: "generated bytes disagree with retained arena bytes", mutate: func(block []byte) {
			generated := binary.LittleEndian.Uint64(block[96:104])
			binary.LittleEndian.PutUint64(block[96:104], generated+1)
		}},
		{name: "retained bytes before arena", mutate: func(block []byte) {
			binary.LittleEndian.PutUint64(block[104:112], uint64(v1ArenaOffset)-1)
		}},
		{name: "retained bytes beyond arena", mutate: func(block []byte) {
			arenaCapacity := binary.LittleEndian.Uint64(block[16:24])
			binary.LittleEndian.PutUint64(block[104:112], uint64(v1ArenaOffset)+arenaCapacity+1)
		}},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			path, _ := writeV1Fixture(t)
			raw, err := os.ReadFile(path)
			if err != nil {
				t.Fatal(err)
			}
			for _, offset := range []int{int(v1SuperblockAOffset), int(v1SuperblockBOffset)} {
				block := raw[offset : offset+int(v1SuperblockBytes)]
				test.mutate(block)
				binary.LittleEndian.PutUint32(block[len(block)-4:], crc32.ChecksumIEEE(block[:len(block)-4]))
			}
			if err := os.WriteFile(path, raw, 0o600); err != nil {
				t.Fatal(err)
			}

			result, err := StreamFileWithResult(path, nil)
			if err == nil || result.Status != SegmentStatusCorrupt || !strings.Contains(err.Error(), "no valid 1.0 superblock") {
				t.Fatalf("result = %+v, error = %v", result, err)
			}
		})
	}
}

